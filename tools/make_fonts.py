#!/usr/bin/env python3
"""Rasterize IBM Plex Mono into classic Mac 'FONT' bitmap resources.

Output: src/fonts.r (Rez source), included in the app's resource fork.

Families (renamed per the OFL Reserved Font Name "Plex"):
  200  MDW Mono              (IBMPlexMono-Regular.ttf)
  201  MDW Mono Bold         (IBMPlexMono-Bold.ttf)
  202  MDW Mono Italic       (IBMPlexMono-Italic.ttf)
  203  MDW Mono Bold Italic  (IBMPlexMono-BoldItalic.ttf)
Resource IDs follow the classic scheme: family * 128 + point size; the
size-0 resource carries only the family name.

Glyphs are rendered with FreeType's monochrome (hinted) mode via Pillow,
one fixed-width cell per character, MacRoman 0x20-0xFF. These are automatic
rasterizations - placeholders until hand-tuned strikes exist.

Usage: python3 tools/make_fonts.py [--fitted]   (needs Pillow; --fitted needs numpy)
  --fitted writes src/fonts_fitted.r: grid-fitted strikes for even stems.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'fonts', 'ibm-plex-mono')
FITTED = '--fitted' in sys.argv          # grid-fitted strikes (tools/fontfit.py)
OUT = os.path.join(ROOT, 'src', 'fonts_fitted.r' if FITTED else 'fonts.r')

FAMILIES = [(200, 'MDW Mono', 'IBMPlexMono-Regular.ttf'),
            (201, 'MDW Mono Bold', 'IBMPlexMono-Bold.ttf'),
            (202, 'MDW Mono Italic', 'IBMPlexMono-Italic.ttf'),
            (203, 'MDW Mono Bold Italic', 'IBMPlexMono-BoldItalic.ttf')]
SIZES = [10, 12, 14, 16, 20]
FIRST, LAST = 0x20, 0xFF


def cell_width(size):
    return int(size * 0.6 + 0.5)        # Plex Mono advance = 600/1000 em


def build(path, size):
    font = ImageFont.truetype(path, size)
    cmap = TTFont(path).getBestCmap()
    asc, desc = font.getmetrics()
    w, h = cell_width(size), asc + desc
    glyphs = []                          # list of (bitmap rows, present)
    for code in range(FIRST, LAST + 1):
        ch = bytes([code]).decode('mac_roman')
        img = Image.new('1', (w, h), 0)
        present = ord(ch) in cmap
        arr = None
        if present and FITTED:
            import numpy as np
            from fontfit import fitted
            arr = fitted(path, size, ch, w, asc, h)
            if arr is not None:
                img = Image.fromarray((arr * 255).astype('uint8')).convert('1')
        if present and (not FITTED or arr is None):
            d = ImageDraw.Draw(img)
            d.fontmode = '1'
            d.text((0, asc), ch, font=font, fill=1, anchor='ls')
        glyphs.append((img, present))
    # missing-glyph symbol: hollow box
    miss = Image.new('1', (w, h), 0)
    ImageDraw.Draw(miss).rectangle([0, 1, w - 2, asc - 1], outline=1)
    glyphs.append((miss, True))

    n = LAST - FIRST + 1
    strike_w = w * len(glyphs)
    row_words = (strike_w + 15) // 16
    strike = Image.new('1', (row_words * 16, h), 0)
    loc, ow = [], []
    for i, (img, present) in enumerate(glyphs):
        strike.paste(img, (i * w, 0))
        loc.append(i * w)
        ow.append((0 << 8) | w if present else 0xFFFF)
    loc.append(len(glyphs) * w)          # end of last glyph
    ow.append(0xFFFF)                    # table terminator
    assert len(loc) == n + 2 and len(ow) == n + 2

    words = []
    bits = strike.load()
    for y in range(h):
        for wx in range(row_words):
            v = 0
            for b in range(16):
                if bits[wx * 16 + b, y]:
                    v |= 0x8000 >> b
            words.append(v)
    ow_tloc = 13 + len(words) + len(loc) - 8
    assert ow_tloc < 0x8000
    header = [0x9000, FIRST, LAST, w, 0, (-desc) & 0xFFFF, w, h, ow_tloc,
              asc, desc, 0, row_words]
    return header + words + loc + ow, (asc, desc, w)


def hexlines(words):
    out, line = [], []
    for v in words:
        line.append('%04X' % (v & 0xFFFF))
        if len(line) == 16:
            out.append('\t$"' + ' '.join(line) + '"')
            line = []
    if line:
        out.append('\t$"' + ' '.join(line) + '"')
    return '\n'.join(out)


def main():
    parts = ['/* Generated by tools/make_fonts.py - do not edit.\n'
             '   MDW Mono: bitmap rasterization of IBM Plex Mono\n'
             '   (SIL Open Font License; "Plex" is a Reserved Font Name). */\n']
    for fam, name, fname in FAMILIES:
        path = os.path.join(SRC, fname)
        parts.append(f'data \'FONT\' ({fam * 128}, "{name}") {{\n}};\n')
        for size in SIZES:
            words, (a, d, w) = build(path, size)
            parts.append(f'/* {name} {size}: ascent {a}, descent {d}, advance {w} */\n'
                         f'data \'FONT\' ({fam * 128 + size}) {{\n{hexlines(words)}\n}};\n')
    with open(OUT, 'w') as f:
        f.write('\n'.join(parts))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
